        <h2>4. Modalità del trattamento</h2>
        <p>
            I dati sono trattati con strumenti informatici e conservati su server con accesso riservato al
            personale autorizzato dell'Associazione (gli amministratori del sito). Adottiamo misure tecniche
            e organizzative adeguate per proteggere i dati da accessi non autorizzati, perdita o
            distruzione, tra cui: connessioni cifrate (HTTPS), password memorizzate con algoritmi di hashing
            sicuri, controllo degli accessi all'area riservata e al pannello di gestione.
        </p>

        <h2>5. Conservazione dei dati</h2>
        <p>
            I dati sono conservati per tutta la durata dell'iscrizione all'Associazione e, successivamente,
            per il periodo necessario ad adempiere a eventuali obblighi di legge. In caso di richiesta di
            iscrizione non approvata, i dati forniti vengono conservati per il tempo strettamente necessario
            alla valutazione della richiesta.
        </p>

